#!/bin/sh
# Regenerates spv.h, the SPIR-V of vkcheck's shaders (copy, dot, order) as C
# arrays, so that tools/vkcheck.c builds with a C compiler alone. Needs
# glslangValidator (glslang-tools on Debian and Ubuntu, glslang elsewhere).
cd "$(dirname "$0")" || exit 1
{
    echo "/* Generated by tools/vkcheck/gen_spv.sh from copy.comp, dot.comp and"
    echo "   order.comp - do not edit. */"
    for s in copy dot order; do
        glslangValidator -V --target-env vulkan1.3 --vn "vkcheck_spv_$s" \
            "$s.comp" -o "$s.spv.tmp" >/dev/null || exit 1
        grep -v '#pragma once' "$s.spv.tmp"
        rm -f "$s.spv.tmp"
    done
} > spv.h.tmp && mv spv.h.tmp spv.h
